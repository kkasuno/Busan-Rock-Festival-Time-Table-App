import ts from "typescript";
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const source = readFileSync(new URL("../app/travel-overlay.tsx", import.meta.url), "utf8");
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, jsx: ts.JsxEmit.React } });
const { travelConnections: connect } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
const show = (id, stage, start, end) => ({ id, stage, start, end, artist: id });
const a = show("a", "samrock", "15:20", "16:00");
const b = show("b", "green", "16:00", "16:50");
assert.equal(connect([a,b],[])[0].arrival,966);
assert.equal(connect([a,{...b,stage:"samrock"}],[]).length,0);
assert.equal(connect([a,{...b,stage:"wave"}],[]).length,0);
assert.equal(connect([a,{...b,start:"16:31"}],[]).length,0);
assert.equal(connect([a,{...b,start:"15:50"}],[]).length,0);
assert.equal(connect([a,b,show("c","river","15:30","16:10")],[]).length,0);
assert.equal(connect([a,b],[{start:"16:00",end:"16:30"}]).length,0);
assert.equal(connect([{...a,stage:"green"},{...b,stage:"samrock"}],[])[0].arrival,966);
assert.equal(connect([a,{...b,stage:"river"}],[])[0].arrival,973);
assert.equal(connect([a,{...b,stage:"hidden"}],[])[0].arrival,968);
console.log("PASS: walking durations, reverse routes, same stage, unknown route, gaps, conflicts, personal plans.");
